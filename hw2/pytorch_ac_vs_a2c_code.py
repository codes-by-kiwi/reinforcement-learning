import torch
import torch.nn as nn
import torch.optim as optim
import torch.nn.functional as F
import gym
import numpy as np

class ActorCritic(nn.Module):
    def __init__(self, state_dim, action_dim, hidden_dim=128):
        super().__init__()
        self.fc1 = nn.Linear(state_dim, hidden_dim)
        self.shared_fc2 = nn.Linear(hidden_dim, hidden_dim)
        self.policy_head = nn.Linear(hidden_dim, action_dim)  # Actor
        self.value_head = nn.Linear(hidden_dim, 1)             # Critic

    def forward(self, state):
        x = F.relu(self.fc1(state))
        action_probs = F.softmax(self.policy_head(x), dim=-1)
        state_value = self.value_head(x)
        return action_probs, state_value

def train_actor_critic(config, env_name="CartPole-v1", episodes=2000):
    env = gym.make(env_name)
    state_dim = env.observation_space.shape[0]
    action_dim = env.action_space.n

    model = ActorCritic(state_dim, action_dim, hidden_dim=config["neurons"])
    optimizer = optim.AdamW(model.parameters(), lr=config["lr"])
    gamma = config["gamma"]

    rewards = []

    for episode in range(episodes):
        state, _ = env.reset()
        total_reward = 0
        done = False

        while not done:
            state_tensor = torch.tensor(state, dtype=torch.float32)
            action_probs, state_value = model(state_tensor)
            dist = torch.distributions.Categorical(action_probs)
            action = dist.sample()

            next_state, reward, terminated, truncated, _ = env.step(action.item())
            done = terminated or truncated
            total_reward += reward

            next_state_tensor = torch.tensor(next_state, dtype=torch.float32)
            _, next_state_value = model(next_state_tensor)

            target_value = reward + (0 if done else gamma * next_state_value.item())
            advantage = target_value - state_value.item()

            actor_loss = -dist.log_prob(action) * advantage
            critic_loss = F.mse_loss(state_value.squeeze(), torch.tensor(target_value))
            loss = actor_loss + critic_loss

            optimizer.zero_grad()
            loss.backward()
            optimizer.step()

            state = next_state

        rewards.append(total_reward)

        if (episode + 1) % 100 == 0:
            avg = np.mean(rewards[-100:])
            print(f"[{config}] Episode {episode+1}, Last 100 Avg Reward: {avg:.1f}")

    env.close()
    return rewards


