# Define global reward tracker
from torch.distributions import Categorical
import numpy as np
episode_rewards_A2c = []

def train_advantage_actor_critic(env_name="CartPole-v1", episodes=3000, gamma=0.99, lr=0.001, hidden_dim=128):
    env = gym.make(env_name)
    state_dim = env.observation_space.shape[0]
    action_dim = env.action_space.n

    model = ActorCritic(state_dim, action_dim, hidden_dim)
    optimizer = optim.Adam(model.parameters(), lr=lr)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model.to(device)

    for episode in range(episodes):
        state, _ = env.reset()
        done = False
        total_reward = 0

        log_probs = []
        values = []
        rewards = []

        while not done:
            state_tensor = torch.tensor(state, dtype=torch.float32).to(device)
            action_probs, state_value = model(state_tensor)
            dist = Categorical(action_probs)
            action = dist.sample()

            next_state, reward, terminated, truncated, _ = env.step(action.item())
            done = terminated or truncated

            log_probs.append(dist.log_prob(action))
            values.append(state_value)
            rewards.append(reward)

            state = next_state
            total_reward += reward

        # Compute returns and advantages
        returns = []
        G = 0
        for r in reversed(rewards):
            G = r + gamma * G
            returns.insert(0, G)
        returns = torch.tensor(returns, dtype=torch.float32).to(device)
        values = torch.cat(values).squeeze()

        # Normalize advantages
        advantages = returns - values.detach()
        advantages = (advantages - advantages.mean()) / (advantages.std() + 1e-8)

        # Compute loss
        log_probs = torch.stack(log_probs)
        actor_loss = - (log_probs * advantages).sum()
        critic_loss = F.mse_loss(values, returns)
        loss = actor_loss + critic_loss

        # Backpropagation
        optimizer.zero_grad()
        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
        optimizer.step()

        episode_rewards_A2c.append(total_reward)
        print(f"Episode {episode}, Total Reward: {total_reward}")

    env.close()

    return episode_rewards_A2c

train_advantage_actor_critic()

