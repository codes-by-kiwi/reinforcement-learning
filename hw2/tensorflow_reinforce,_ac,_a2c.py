"""Advantage Actor-Critic (A2C) Implementation"""

env = gym.make('CartPole-v1')
state_dim = env.observation_space.shape[0]
action_dim = env.action_space.n
theta_limit = env.theta_threshold_radians
hidden_dim = 32

# === A2C Network ===
class A2CAgent:
    def __init__(self, state_dim, action_dim, hidden_dim, gamma=0.99, lr=0.001):
        self.gamma = gamma
        self.a_dim = action_dim

        # Actor: policy network π(a|s)
        self.actor = Sequential([
            Dense(hidden_dim, activation='relu', input_shape=(state_dim,)),
            Dense(action_dim, activation='softmax')
        ])

        # Critic: value network V(s)
        self.critic = Sequential([
            Dense(hidden_dim, activation='relu', input_shape=(state_dim,)),
            Dense(1, activation='linear')
        ])

        self.actor_optimizer = Adam(learning_rate=lr)
        self.critic_optimizer = Adam(learning_rate=lr)

    def get_action(self, state):
        state = state.reshape(1, -1)
        action_probs = self.actor(state).numpy().flatten()
        return np.random.choice(self.a_dim, p=action_probs)

    def train(self, states, actions, rewards, next_states, dones):
      states = tf.convert_to_tensor(states, dtype=tf.float32)
      next_states = tf.convert_to_tensor(next_states, dtype=tf.float32)
      actions = tf.convert_to_tensor(actions, dtype=tf.int32)
      rewards = tf.convert_to_tensor(rewards, dtype=tf.float32)
      dones = tf.convert_to_tensor(dones, dtype=tf.float32)

      # === Compute target and advantage ===
      with tf.GradientTape() as tape_critic:
          values = tf.squeeze(self.critic(states), axis=1)
          next_values = tf.squeeze(self.critic(next_states), axis=1)
          targets = rewards + self.gamma * next_values * (1 - dones)
          critic_loss = tf.reduce_mean((targets - values) ** 2)

      critic_grads = tape_critic.gradient(critic_loss, self.critic.trainable_variables)
      self.critic_optimizer.apply_gradients(zip(critic_grads, self.critic.trainable_variables))

      # recompute current value predictions again
      with tf.GradientTape() as tape_actor:
          values = tf.squeeze(self.critic(states), axis=1)
          probs = self.actor(states)
          action_masks = tf.one_hot(actions, depth=self.a_dim)
          selected_probs = tf.reduce_sum(probs * action_masks, axis=1)
          advantages = targets - values
          actor_loss = -tf.reduce_mean(tf.math.log(selected_probs + 1e-10) * advantages)

      actor_grads = tape_actor.gradient(actor_loss, self.actor.trainable_variables)
      self.actor_optimizer.apply_gradients(zip(actor_grads, self.actor.trainable_variables))

      return actor_loss.numpy(), critic_loss.numpy()

agent = A2CAgent(state_dim, action_dim, hidden_dim=hidden_dim)
episodes = 1000
max_steps = 500
total_rewards = []

# === Training Loop ===
for ep in range(episodes):
    state = env.reset()
    done = False
    episode_reward = 0
    episode_data = []

    for step in range(max_steps):
        action = agent.get_action(state)
        next_state, _, done, _ = env.step(action)

        # Reward
        reward = 1
        episode_data.append((state, action, reward, next_state, done))
        episode_reward += reward
        state = next_state

    # End of episode

    episode_data = np.array(episode_data, dtype=object)
    states = np.vstack(episode_data[:, 0])
    actions = np.array(episode_data[:, 1], dtype=np.int32)
    rewards = np.array(episode_data[:, 2], dtype=np.float32)
    next_states = np.vstack(episode_data[:, 3])
    dones = np.array(episode_data[:, 4], dtype=np.float32)


    actor_loss, critic_loss = agent.train(states, actions, rewards, next_states, dones)
    #print(f"[DEBUG] Episode {ep}, Episode reward: {episode_reward}")
    total_rewards.append(episode_reward)

    if ep % 50 == 0 and ep != 0:
        print(f"Episode {ep}, Steps: {step+1}, Avg Reward (50): {np.mean(total_rewards[-50:]):.2f}, Avg Reward: {np.mean(total_rewards):.2f}, Actor Loss: {actor_loss:.4f}, Critic Loss: {critic_loss:.4f}")

