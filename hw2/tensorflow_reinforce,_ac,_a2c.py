# === Reinforcement Policy Network ===
class PolicyNet:
    def __init__(self, learn_rate, state_dim, action_dim, hidden_dim, discount_ratio=0.99):
        self.lr = learn_rate
        self.gamma = discount_ratio
        self.s_dim = state_dim
        self.a_dim = action_dim
        self.h_dim = hidden_dim

        self.model = Sequential([
            Dense(self.h_dim, activation='relu', input_shape=(self.s_dim,)), # use 1 hidden layer
            Dense(self.a_dim, activation='softmax') # use softmax to output probability
        ])
        self.optimizer = Adam(learning_rate=self.lr)

    # calculate gradients
    def calc_grad(self, state_input, action_holder, reward_holder):
        with tf.GradientTape() as tape:
            probs = self.model(state_input)
            action_indices = tf.stack([tf.range(tf.shape(probs)[0]), action_holder], axis=1) # get index and action for each step
            selected_action_probs = tf.gather_nd(probs, action_indices) # get action's probability
            loss = -tf.reduce_mean(tf.math.log(selected_action_probs + 1e-10) * reward_holder) # calculate loss
        grads = tape.gradient(loss, self.model.trainable_variables)
        return grads, loss

    # do gradient descent
    def update(self, grads):
        self.optimizer.apply_gradients(zip(grads, self.model.trainable_variables))

    # calculate Monte Carlo return
    def calc_returns(self, rewards):
        discounted = np.zeros_like(rewards, dtype=np.float32) #
        running_add = 0
        for t in reversed(range(len(rewards))):
            running_add = running_add * self.gamma + rewards[t]
            discounted[t] = running_add
        # Normalize
        #discounted = (discounted - np.mean(discounted)) / (np.std(discounted) + 1e-8)
        return discounted

# === Training Setup ===
# maps action to prob
