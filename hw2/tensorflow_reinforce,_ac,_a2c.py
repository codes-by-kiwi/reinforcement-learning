# === Actor-Critic Neural Network ===
class ActorCriticNet:
    def __init__(self, state_dim, action_dim, hidden_dim, gamma=0.99, lr=0.001):
        self.gamma = gamma
        self.actor = Sequential([
            Dense(hidden_dim, activation='relu', input_shape=(state_dim,)),
            Dense(action_dim, activation='softmax')
        ])
        self.critic = Sequential([
            Dense(hidden_dim, activation='relu', input_shape=(state_dim,)),
            Dense(1, activation='linear')
        ])
        self.actor_opt = Adam(learning_rate=lr)
        self.critic_opt = Adam(learning_rate=lr)

    def calc_returns(self, rewards):
        discounted = np.zeros_like(rewards, dtype=np.float32)
        running_add = 0
        for t in reversed(range(len(rewards))):
            running_add = rewards[t] + self.gamma * running_add
            discounted[t] = running_add
        return discounted

    def train(self, states, actions, returns):
        states = tf.convert_to_tensor(states, dtype=tf.float32)
        actions = tf.convert_to_tensor(actions, dtype=tf.int32)
        returns = tf.convert_to_tensor(returns, dtype=tf.float32)

        # Critic training
        with tf.GradientTape() as tape_critic:
            values = tf.squeeze(self.critic(states), axis=1)
            critic_loss = tf.reduce_mean((returns - values)**2)
        critic_grads = tape_critic.gradient(critic_loss, self.critic.trainable_variables)
        self.critic_opt.apply_gradients(zip(critic_grads, self.critic.trainable_variables))

        with tf.GradientTape() as tape_actor:
            probs = self.actor(states)
            action_masks = tf.one_hot(actions, depth=probs.shape[1])
            selected_probs = tf.reduce_sum(probs * action_masks, axis=1)
            actor_loss = -tf.reduce_mean(tf.math.log(selected_probs + 1e-10) * returns)
        actor_grads = tape_actor.gradient(actor_loss, self.actor.trainable_variables)
        self.actor_opt.apply_gradients(zip(actor_grads, self.actor.trainable_variables))

        return actor_loss.numpy(), critic_loss.numpy()

agent = ActorCriticNet(state_dim=state_dim, action_dim=action_dim, hidden_dim=hidden_dim)
episodes = 1000
max_steps = 500
total_rewards = []

# === Training ===
for ep in range(episodes):
    state = env.reset()
