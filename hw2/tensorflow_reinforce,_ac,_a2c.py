    steps = 0

    while not done and steps < max_steps:
        steps += 1
        state_tensor = state.reshape(1, -1)
        action_probs = agent.actor(state_tensor).numpy().flatten()
        action = np.random.choice(action_dim, p=action_probs)
        next_state, _, done, _ = env.step(action)

        reward = 1
        episode_data.append((state, action, reward))
        ep_reward += reward
        state = next_state

    # End of episode
    episode_data = np.array(episode_data, dtype=object)
    rewards = np.array([r for (_, _, r) in episode_data])
    returns = agent.calc_returns(rewards)

    states = np.vstack(episode_data[:, 0])
    actions = np.array(episode_data[:, 1], dtype=np.int32)

    actor_loss, critic_loss = agent.train(states, actions, returns)
    total_rewards.append(ep_reward)

    if ep % 50 == 0 and ep != 0:
        print(f"Ep {ep}, Steps: {steps}, Avg Reward (50): {np.mean(total_rewards[-50:]):.2f}, Avg Reward: {np.mean(total_rewards):.2f}, Actor Loss: {actor_loss:.4f}, Critic Loss: {critic_loss:.4f}")

