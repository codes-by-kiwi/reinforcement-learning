def random_weight_initialization(no_of_features, action_space, neurons=128):
    global weight_1st_HL, weight_2nd_HL

    #make into leaf tensors below
    weight_1st_HL = torch.nn.Parameter(init.xavier_uniform_(torch.rand(no_of_features, neurons)), requires_grad=True)
    weight_2nd_HL = torch.nn.Parameter(init.xavier_uniform_(torch.rand(neurons, action_space)), requires_grad=True)

def forward_pass(current_state, training=True, temperature=1.0):

    intermediate_out = torch.relu(torch.matmul(current_state, weight_1st_HL))

    if training:
        intermediate_out = torch.nn.Dropout(p=0.2)(intermediate_out)

    action_logits = torch.matmul(intermediate_out, weight_2nd_HL)

    action_logits = action_logits/temperature

    action_probabilities = torch.softmax(action_logits, dim=-1)

    if torch.isnan(action_probabilities).any():
        print("Warning: NaN values found in the action probabilities, please account for this.")
        action_probabilities = torch.nan_to_num(action_probabilities, nan=1e-9)

    return action_probabilities

#discount factor here changes based on how far ahead you are in the future

def compute_discounted_return(rewards, gamma=0.99):
    Discounted_return = []
    R = 0

    for r in reversed(rewards):
        R = r + gamma * R
        Discounted_return.insert(0,R)
    return Discounted_return

