def run_rf_algo_configs(gym_env, config_name, config, total_Steps=1000000):
    global weight_1st_HL, weight_2nd_HL
    random_weight_initialization(no_of_features, action_space, neurons=config["neurons"])

    optimizer = optim.Adam([weight_1st_HL, weight_2nd_HL], lr=config["lr"], weight_decay = 0.01)
    episode_rewards = []
    step_rewards = []
    all_rewards = []

    state, _ = gym_env.reset()
    state = torch.tensor(state, dtype=torch.float32)
    log_probs = []
    rewards = []

    step_count = 0
    episode_count = 0

    while step_count < total_Steps:
        action_probs = forward_pass(state)


        m = Categorical(action_probs)
        action = m.sample()

        log_prob = m.log_prob(action)
        next_state, reward, terminated, truncated, _ = gym_env.step(action.item())
        done = terminated or truncated
        next_state = torch.tensor(next_state, dtype=torch.float32)

        log_probs.append(log_prob)
        rewards.append(reward)
        step_rewards.append(reward)
        step_count += 1

        if not done:
          state = next_state

        if done:
          returns = compute_discounted_return(rewards, config["gamma"])
          returns = torch.tensor(returns, dtype=torch.float32)
          returns = (returns - returns.mean()) / (returns.std() + 1e-9)

          policy_loss = []
          for log_prob, R in zip(log_probs, returns):
            policy_loss.append(-log_prob * R)

          optimizer.zero_grad()
          loss = torch.stack(policy_loss).sum()
          loss.backward()
          torch.nn.utils.clip_grad_norm_([weight_1st_HL, weight_2nd_HL], max_norm=1.0)
          optimizer.step()

          episode_rewards.append(sum(rewards))
          all_rewards.extend(step_rewards)
          step_rewards = []

          state, _ = gym_env.reset()
          state = torch.tensor(state, dtype=torch.float32)
          log_probs = []
          rewards = []
          episode_count += 1

          if episode_count % 100 == 0:
            avg_reward = np.mean(episode_rewards[-100:])
            print(f"Config {config_name}: Step {step_count}/{total_Steps} | Episode {episode_count} | Last 100 avg reward: {avg_reward:.1f}")

    return episode_rewards,all_rewards

